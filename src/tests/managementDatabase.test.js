async function bootstrap(database, idType = 'uuid', photoType = 'jsonb', zipType = 'text', includeCreation = true) {
  await database.exec(`
    create role anon; create role authenticated; create role service_role bypassrls;
    create schema auth; create schema storage;
    create table auth.users (id uuid primary key, email text unique, email_confirmed_at timestamptz, created_at timestamptz default now());
    create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
    grant usage on schema auth, public, storage to anon, authenticated, service_role;
    create table public.places (id ${idType} ${idType === 'uuid' ? 'default gen_random_uuid()' : 'generated by default as identity'} primary key, name text, "urlSlug" text unique, tagline text, description text,
      website text, address text, city text, state text, zip ${zipType}, "coverPhoto" text, photos ${photoType}, "isFeatured" boolean default false,
      "isVerified" boolean default false, latitude double precision, longitude double precision);
    grant all on public.places to public, anon, authenticated, service_role;
    create policy legacy_places on public.places for all using (true) with check (true);
    create table storage.buckets (id text primary key, name text, public boolean, file_size_limit bigint, allowed_mime_types text[]);
    create table storage.objects (id uuid primary key default gen_random_uuid(), bucket_id text, name text);
    alter table storage.objects enable row level security;
    grant all on storage.objects to anon, authenticated, service_role;
    create policy legacy_permissive_storage on storage.objects for all using (true) with check (true);
  `);
  await database.exec(migration);
  await database.exec(conflictMigration);
  await database.exec(adminMigration);
  if (includeCreation) await database.exec(createMigration);
  await database.exec(notificationMigration);
  await database.exec(launchMigration);
}

