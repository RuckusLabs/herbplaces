test('billing events are idempotent, retries retain the grace deadline, and old events cannot regress recovery', async () => {
  await asRole('service_role', null, async () => {
    const now = new Date(); const paid = new Date(Date.now() + 86400000).toISOString();
    const event = (id, created, status, failedAt = null) => rpc('apply_billing_event', [id, created, ids.place, 'cus_place', 'sub_place', status, paid, failedAt, false]);
    await event('evt_first', 10, 'past_due', now.toISOString());
    const first = (await db.query('select grace_ends_at from public.place_subscriptions where place_id=$1', [ids.place])).rows[0].grace_ends_at;
    await event('evt_retry', 11, 'past_due', new Date(now.getTime() + 86400000).toISOString());
    const retry = (await db.query('select grace_ends_at from public.place_subscriptions where place_id=$1', [ids.place])).rows[0].grace_ends_at;
    assert.equal(first.toISOString(), retry.toISOString());
    await event('evt_paid', 20, 'active'); await event('evt_paid', 20, 'past_due'); await event('evt_delayed', 12, 'past_due');
    const row = (await db.query('select status,grace_ends_at from public.place_subscriptions where place_id=$1', [ids.place])).rows[0];
    assert.equal(row.status, 'active'); assert.equal(row.grace_ends_at, null);
    assert.equal((await db.query('select count(*)::int as count from public.billing_events')).rows[0].count, 4);
  });
});

