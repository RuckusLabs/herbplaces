test('removal locks block new access and publishing; cancellation restores access', async () => {
  await db.exec('begin');
  try {
    const reservation = await rpc('prepare_user_removal', [ids.admin, ids.teammate, 'teammate@example.com']);
    await db.query("select set_config('request.jwt.claim.sub', $1, true)", [ids.teammate]);
    assert.equal((await db.query('select place_management_private.confirmed_user() as allowed')).rows[0].allowed, false);
    assert.equal(await rpc('management_service_access', [ids.place, ids.teammate]), null);
    // Use savepoints so expected failures do not abort this outer transaction.
    for (const query of [
      ['insert into public.place_memberships(place_id,user_id) values($1,$2)', [ids.otherPlace, ids.teammate]],
      ['insert into public.site_admins(user_id) values($1)', [ids.teammate]],
      ['insert into public.place_invitations(place_id,email) values($1,$2)', [ids.otherPlace, 'teammate@example.com']],
    ]) {
      await db.exec('savepoint denied'); await assert.rejects(db.query(...query), /being removed/); await db.exec('rollback to denied');
    }
    await db.exec('savepoint denied'); await assert.rejects(rpc('finish_user_removal', [ids.teammate, reservation.token]), /not completed/); await db.exec('rollback to denied');
    await rpc('finish_user_removal', [ids.teammate, reservation.token, true]);
    assert.equal((await db.query('select place_management_private.confirmed_user() as allowed')).rows[0].allowed, true);
  } finally { await db.exec('rollback'); }
});

